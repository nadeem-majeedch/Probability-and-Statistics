def build(name: str) -> dict:
    number, title, csv, minutes, sections, label = SPECS[name]
    if name.startswith("p09"):
        cells = [("md", f"""# Capstone — {title}

**Starter notebook.** This is one investigation in twelve sections. Read the full brief on
the course site first; it contains the marking rubric.

- **Dataset:** `docs/data/projects/{csv}`
- **Suggested time:** {minutes} hours of analysis, plus report writing
"""), ("code", HEADER.format(csv=csv)), ("code", """df.info()
df.describe(include="all").T""")] + sections + footer()
    else:
        cells = intro(number, title, csv, minutes, len(sections)) + sections + footer()
    return nb(cells)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    check = "--check" in sys.argv
    stale = []
    for name in SPECS:
        path = OUT / name
        text = json.dumps(build(name), indent=1, ensure_ascii=False) + "\n"
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="")
            doc = json.loads(path.read_text(encoding="utf-8"))
            print(f"{name:34s} cells={len(doc['cells']):2d} valid=yes")
    if check:
        if stale:
            print("out of date:", ", ".join(stale))
            return 1
        print(f"all {len(SPECS)} notebooks match a fresh build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

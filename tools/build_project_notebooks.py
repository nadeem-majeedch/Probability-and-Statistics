def nb(cells: list[tuple[str, str]]) -> dict:
    out_cells = []
    for i, (kind, text) in enumerate(cells):
        source = text.strip("\n").splitlines(keepends=True)
        if kind == "md":
            out_cells.append({"cell_type": "markdown", "id": f"c{i}", "metadata": {},
                              "source": source})
        else:
            out_cells.append({"cell_type": "code", "id": f"c{i}", "metadata": {},
                              "execution_count": None, "outputs": [], "source": source})
    return {
        "cells": out_cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.11"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


